/**
 * Search the verified coins by query string (symbol or name)
 */
export const searchCmcCoins = (query = '') => {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return VERIFIED_CMC_COINS.slice(0, 24);

  // Exact symbol match ranks highest
  const exact = [];
  const symbolStarts = [];
  const nameStarts = [];
  const contains = [];

  for (const c of VERIFIED_CMC_COINS) {
    const sym = c.symbol.toLowerCase();
    const name = c.name.toLowerCase();

    if (sym === q) {
      exact.push(c);
    } else if (sym.startsWith(q)) {
      symbolStarts.push(c);
    } else if (name.startsWith(q)) {
      nameStarts.push(c);
    } else if (sym.includes(q) || name.includes(q)) {
      contains.push(c);
    }
  }

  return [...exact, ...symbolStarts, ...nameStarts, ...contains].slice(0, 30);
};
